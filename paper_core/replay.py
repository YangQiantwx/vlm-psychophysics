"""Build or execute a single frozen Qwen, Nemo, Cosmos or Muse trial."""

from argparse import ArgumentParser
from importlib import metadata
import gzip
from hashlib import sha256 as hash_bytes
import json
import os
from pathlib import Path
from urllib.request import urlopen

from PIL import Image

from .media import decoded_sha, read_video
from .scores import dataset, read_json, require, sha256


def checked(root, relative, digest):
    path = (root / relative).resolve()
    require(path.is_relative_to(root.resolve()), 'Media must be below its designated root')
    require(sha256(path) == digest, (relative, 'media SHA-256'))
    return path


def content_entry(kind, path):
    key = kind + '_url'
    return {'type':key, key:{'url':path.as_uri()}}


def frozen_ordered_rgb(study, trial):
    digest = trial.get('decoded_stream_sha256')
    if digest is not None:
        return digest
    manifest = read_json(study/'manifest.json')
    rev = manifest['api_runner']['png_revision']
    repo = manifest['panel']['repo']
    url = f'https://huggingface.co/datasets/{repo}/resolve/{rev}/api-images/v1/index.json.gz'
    with urlopen(url, timeout=60) as response:
        index_bytes = response.read()
    require(hash_bytes(index_bytes).hexdigest()==manifest['api_runner']['png_index_sha256'],
            'Frozen PNG inventory changed')
    source = json.loads(gzip.decompress(index_bytes))['sources'][trial['video_sha256']]
    require(len(source['png_sha256']) == 180, 'Frozen PNG frame count changed')
    return source['rgb_sha256']


def request(args, videos, stills, config):
    trial = videos[args.id]
    v_path = trial.get('path',trial.get('video_path'))
    if args.mode == 'static':
        require(args.variant == 'original', 'Static variants are regenerated by paper_core.media')
        selected = stills[args.id]
        media = [('image',checked(args.data,i['path'],i['sha256'])) for i in selected['images']]
    else:
        selected = trial
        media = [('image',checked(args.data,trial['reference']['path'],trial['reference']['sha256']))] if 'reference' in trial else []
        movie = checked(args.data,v_path,trial['video_sha256'])
        if args.variant == 'axis':
            axis = read_json(args.study/'t3-axis-inputs.json')['inputs'][args.id]
            require(axis['base_sha256']==trial['video_sha256'], 'Axis source SHA')
            movie = checked(args.study,axis['marked_path'],axis['marked_sha256'])
        elif args.variant == 'enlarged':
            zoom = read_json(args.study/'t5-enlarged-inputs.json')['inputs'][args.id]
            require(zoom['original_video_sha256']==trial['video_sha256'], 'Enlargement source SHA')
            enlarged = [(m['type'], checked(args.study,m['path'],m['sha256'])) for m in zoom['media']]
            require([k for k,_ in enlarged] == ['image','video'],'Enlargement media order')
            media, movie = enlarged[:1], enlarged[1][1]
        if args.mode == 'png':
            require(args.variant == 'original','The PNG experiment uses the original source MP4')
            frames = read_video(movie)
            require(decoded_sha(frames) == frozen_ordered_rgb(args.study, selected), 'Ordered video RGB identity')
            frame_dir = args.out/'frames'
            frame_dir.mkdir(exist_ok=True)
            for i, rgb in enumerate(frames):
                png = frame_dir/f'{i:03d}.png'
                Image.fromarray(rgb).save(png)
                media.append(('image',png.resolve()))
        else:
            media.append(('video',movie))
    prompt = selected['prompt']
    if args.mode == 'png':
        prompt = config['frame_prompt_prefix'] + prompt
    choices = ['YES','NO'] if selected['task']=='T5' else ['LEFT','RIGHT']
    return selected, media, prompt, choices


def final_answer(output, tokenizer, choices, thinking):
    if output.finish_reason != 'stop':
        return None
    text = output.text
    if thinking:
        tokens = list(output.token_ids)
        end = tokenizer.encode('</think>',add_special_tokens=False)
        starts = tokenizer.encode('<think>',add_special_tokens=False)
        require(bool(end),'Tokenizer has no reasoning end delimiter')
        ends = [i for i in range(len(tokens)-len(end)+1) if tokens[i:i+len(end)]==end]
        if len(ends)!=1:
            return None
        remainder = tokens[ends[0]+len(end):]
        if starts and any(remainder[i:i+len(starts)]==starts for i in range(len(remainder))):
            return None
        text = tokenizer.decode(remainder,skip_special_tokens=True)
    return text.strip() if text.strip() in choices else None


def execute(args, profile, generation, messages, choices):
    require(args.weights is not None and args.weights.is_dir(), 'Provide the pinned local --weights snapshot')
    require(args.weights.name==profile['checkpoint_revision'], 'Wrong checkpoint revision directory')
    for package, version in profile['packages'].items():
        require(metadata.version(package)==version, (package,'installed version differs',version))
    os.environ.update(profile['environment'])
    from vllm import LLM, SamplingParams
    from vllm.sampling_params import StructuredOutputsParams
    import torch

    if profile['torch_num_threads'] is not None:
        torch.set_num_threads(profile['torch_num_threads'])
    kwargs = dict(profile['engine'],model=str(args.weights.resolve()))
    # The overlays specify host-local media and packaged worker hook paths.
    roots = [args.data.resolve(), args.study.resolve(), args.out.resolve()]
    kwargs['allowed_local_media_path'] = os.path.commonpath(roots)
    kwargs['media_io_kwargs'] = profile['media_io_kwargs']
    if isinstance(kwargs.get('cpu_offload_params'),list):
        kwargs['cpu_offload_params'] = set(kwargs['cpu_offload_params'])
    if 'tokenizer_revision' in profile:
        require(args.tokenizer and args.tokenizer.name==profile['tokenizer_revision'],'Provide pinned --tokenizer')
        kwargs['tokenizer'] = str(args.tokenizer.resolve())
    settings = SamplingParams(**generation,structured_outputs=StructuredOutputsParams(choice=choices))
    cot = args.arm=='cot'
    chat = {}
    thinking = args.arm in {'low','cot'}
    if cot:
        settings.thinking_token_budget=profile['thinking_tokens']
    elif args.model=='qwen':
        chat = {'enable_thinking':args.arm=='low'}
        if thinking:
            chat['reasoning_effort']='low'
    elif args.model=='nemo':
        chat=profile['chat_template_kwargs'][args.arm]
    engine = LLM(**kwargs)
    result, = engine.chat(messages, sampling_params=settings, use_tqdm=False,
                         add_generation_prompt=not cot, continue_final_message=cot,
                         chat_template_kwargs=chat, mm_processor_kwargs=profile['request_mm_processor_kwargs'])
    output, = result.outputs
    return {'answer': final_answer(output,engine.get_tokenizer(),choices,thinking),
            'finish_reason':output.finish_reason,'prompt_token_ids':list(result.prompt_token_ids),
            'answer_token_ids':list(output.token_ids),'raw_answer':output.text}


def main():
    ap=ArgumentParser(description=__doc__)
    ap.add_argument('--study',type=Path,required=True)
    ap.add_argument('--data',type=Path,required=True)
    ap.add_argument('--id',required=True)
    ap.add_argument('--model',choices=('qwen','nemo','cosmos','glimmer'),required=True)
    ap.add_argument('--mode',choices=('video','static','png'),default='video')
    ap.add_argument('--arm',choices=('off','low','cot','direct'),required=True)
    ap.add_argument('--variant',choices=('original','axis','enlarged'),default='original')
    ap.add_argument('--weights',type=Path)
    ap.add_argument('--tokenizer',type=Path)
    ap.add_argument('--out',type=Path,required=True)
    ap.add_argument('--execute',action='store_true')
    args=ap.parse_args()
    spec=read_json(args.study/'manifest.json')
    selected=None
    for key in ('base','panel'):
        if sha256(args.data/'dataset-index.json')==spec[key]['index_sha256']:
            selected=spec[key]['index_sha256']
    require(selected is not None,'Pin the base or panel dataset revision')
    cfg=read_json(args.study/'model-configs.json')
    profile_key = ('qwen-png' if args.mode=='png' else 'qwen-native') if args.model=='qwen' else f'{args.model}-t5'
    profile = cfg['pinned_profiles'].get(profile_key,{})
    if args.model=='qwen':
        require(args.arm in {'off','low'},'Qwen supports the frozen off/low settings')
    elif args.model=='glimmer':
        require(args.arm=='direct' and args.mode!='png','Muse uses native label-only responses')
    else:
        arms = {'off','low'} if args.model=='nemo' else {'direct','cot'}
        require(args.mode=='video' and args.arm in arms and args.variant=='original', 'Use the T5 native recipe')
    args.out.mkdir(parents=True,exist_ok=True)
    videos, stills=dataset(args.data,selected)
    trial, media, prompt, choices=request(args,videos,stills,profile)
    if args.model in {'nemo','cosmos'}:
        require(trial['task']=='T5','The submitted control is a T5 recipe')
    if args.arm=='cot':
        prompt += profile['cot_prompt_suffix']
    messages=[{'role':'user','content':[*[content_entry(k,p) for k,p in media], {'type':'text','text':prompt}]}]
    if args.arm=='cot':
        messages.append({'role':'assistant','content':profile['assistant_prefill']})
    plan=dict(sample_id=args.id,model=args.model,mode=args.mode,arm=args.arm,variant=args.variant,
              media_sha256=[sha256(p) for _,p in media],truth=trial['truth'],messages=messages)
    (args.out/'request.json').write_text(json.dumps(plan,indent=2)+'\n')
    if args.execute:
        if args.model=='glimmer':
            from vlm_psychophysics import glimmer
            require(args.weights is not None and args.weights.name==glimmer.REVISION,'Use the pinned Muse checkpoint')
            case = {'sample_id':args.id,'task':trial['task'],'domain':trial['domain'],'truth':trial['truth'],
                    'modality':args.mode,'choices':choices,'prompt':prompt,'case_id':args.id,
                    'images':[{'path':str(p),'sha256':sha256(p)} for k,p in media if k=='image']}
            if args.mode=='video':
                movie=media[-1][1]
                case.update(video_path=str(movie),video_sha256=sha256(movie))
            # Session records model and processor identities alongside its output.
            case['prompt_sha256']=hash_bytes(prompt.encode()).hexdigest()
            case['model_input_sha256']=hash_bytes(json.dumps([prompt,plan['media_sha256'],choices],separators=(',',':')).encode()).hexdigest()
            session=glimmer.Session(args.weights,args.data,args.out)
            try:
                answer=session.run(case,force_deep=True)
            finally:
                session.close()
        else:
            answer=execute(args,profile,cfg['generation_default'],messages,choices)
        (args.out/'answer.json').write_text(json.dumps(answer,indent=2)+'\n')
    print(f'Verified {len(media)} ordered media items for {args.id}.')


if __name__=='__main__':
    main()
